#!/usr/bin/env bash
# Reproducible provisioning of the local Maven AAR (libs/repo).
#
# The sherpa-onnx runtime is not a normal Maven Central artifact: the app resolves
# `com.k2fsa.sherpa:onnx:2.0.1` from the gitignored local maven repo `libs/repo/`,
# which must be rebuilt after a fresh clone. Produce it always from the pinned
# upstream release, verify the published SHA-256, and never "succeed" silently
# when the AAR cannot be reproduced.
#
# Usage:
#   ./scripts/prepare-deps.sh            # verify or download+install
#   SHA256=no sha256sum ./scripts/prepare-deps.sh  # record a new pin after an upgrade
set -euo pipefail

AAR_GROUP="com.k2fsa.sherpa"
AAR_ARTIFACT="onnx"
AAR_VERSION="2.0.1"
AAR_URL="https://github.com/k2-fsa/sherpa-onnx/releases/download/v${AAR_VERSION}/sherpa-onnx-${AAR_VERSION}.aar"
AAR_BYTES=49441341
AAR_SHA256="${SHA256:-a8d09d1d32f3eb8520482c6d3d43fae674681c5b050385967c70a3c2c9bf0ee7}"
REPO_DIR="$(cd "$(dirname "$0")/.." && pwd)/libs/repo"
REL_DIR="${REPO_DIR}/$(echo "${AAR_GROUP}" | tr '.' '/')/${AAR_ARTIFACT}/${AAR_VERSION}"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

existing="${REL_DIR}/${AAR_ARTIFACT}-${AAR_VERSION}.aar"

if [[ -f "${existing}" ]]; then
  if sha256sum -c <(printf '%s  %s\n' "${AAR_SHA256}" "${existing}") >/dev/null 2>&1; then
    echo "prepare-deps: ${existing} already matches pinned SHA-256; nothing to do."
    exit 0
  fi
  echo "prepare-deps: existing AAR hash mismatch with pin ${AAR_SHA256}, re-provisioning." >&2
  rm -f "${existing}"
fi

echo "prepare-deps: downloading ${AAR_URL}"
curl -fsSL --retry 3 -o "${TMP}/${AAR_ARTIFACT}-${AAR_VERSION}.aar" "${AAR_URL}"

actual_size="$(stat -c %s "${TMP}/${AAR_ARTIFACT}-${AAR_VERSION}.aar")"
if [[ "${actual_size}" != "${AAR_BYTES}" ]]; then
  echo "prepare-deps: FATAL downloaded size ${actual_size} != published ${AAR_BYTES} bytes; aborting." >&2
  exit 1
fi

if ! echo "${AAR_SHA256}" | sha256sum -c <(printf '%s  %s\n' "${AAR_SHA256}" "${TMP}/${AAR_ARTIFACT}-${AAR_VERSION}.aar") >/dev/null 2>&1; then
  actual="$(sha256sum "${TMP}/${AAR_ARTIFACT}-${AAR_VERSION}.aar" | cut -d' ' -f1)"
  echo "prepare-deps: FATAL SHA-256 mismatch: expected ${AAR_SHA256}, got ${actual}; aborting." >&2
  exit 1
fi

mkdir -p "${REL_DIR}"
install -m 0644 "${TMP}/${AAR_ARTIFACT}-${AAR_VERSION}.aar" "${existing}"
sed "s|@ARTIFACT@|${AAR_ARTIFACT}|; s|@GROUP@|${AAR_GROUP}|; s|@VERSION@|${AAR_VERSION}|" \
  <(cat <<'POM'
<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by scripts/prepare-deps.sh; upstream: ${AAR_URL} licence Apache-2.0. -->
<project><modelVersion>4.0.0</modelVersion>
<groupId>@GROUP@</groupId><artifactId>@ARTIFACT@</artifactId><version>@VERSION@</version>
<packaging>aar</packaging><name>sherpa-onnx Android AAR (pinned upstream release)</name></project>
POM
) > "${REL_DIR}/${AAR_ARTIFACT}-${AAR_VERSION}.pom"
sha1sum "${existing}" | awk '{printf $1}' > "${existing}.sha1"
sha1sum "${REL_DIR}/${AAR_ARTIFACT}-${AAR_VERSION}.pom" | awk '{printf $1}' > "${REL_DIR}/${AAR_ARTIFACT}-${AAR_VERSION}.pom.sha1"

echo "prepare-deps: installed ${existing}"
